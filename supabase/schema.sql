-- A. VERIFY TABLE PIN WITH 5-ATTEMPT 5-MINUTE LOCKOUT
CREATE OR REPLACE FUNCTION public.verify_table_pin(
    p_table_code TEXT,
    p_pin TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_table RECORD;
    v_session RECORD;
    v_lock_remaining_seconds INTEGER;
BEGIN
    -- 1. Find table by code
    SELECT * INTO v_table
    FROM public.cafe_tables
    WHERE LOWER(table_code) = LOWER(p_table_code);

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', false,
            'message', 'Invalid table code. Please check the QR code or talk to manager.'
        );
    END IF;

    -- 2. Find active session for this table
    SELECT * INTO v_session
    FROM public.table_sessions
    WHERE table_id = v_table.id AND status = 'ACTIVE'
    ORDER BY opened_at DESC
    LIMIT 1;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'success', false,
            'message', 'Table is not currently open. Please ask the manager to generate a PIN.'
        );
    END IF;

    -- 3. Check if table is locked due to 5 wrong attempts
    IF (v_session.failed_attempts >= 5) OR (v_session.locked_until IS NOT NULL AND v_session.locked_until > now()) THEN
        RETURN jsonb_build_object(
            'success', false,
            'locked', true,
            'permanent_lock', true,
            'attempts_left', 0,
            'message', '5 बार गलत पिन दर्ज किया गया। यह पिन ब्लॉक हो गया है। कृपया मैनेजर से नया पिन लें। (5 wrong attempts exceeded. This PIN is blocked. Please get a new PIN from the manager.)'
        );
    END IF;

    -- 4. Check PIN match
    IF v_session.pin_code = p_pin THEN
        -- Success: reset failed attempts
        UPDATE public.table_sessions
        SET failed_attempts = 0,
            locked_until = NULL
        WHERE id = v_session.id;

        RETURN jsonb_build_object(
            'success', true,
            'session_token', v_session.session_token,
            'session_id', v_session.id,
            'table_id', v_table.id,
            'table_number', v_table.table_number,
            'table_code', v_table.table_code
        );
    ELSE
        -- Incorrect PIN: increment failed attempts
        UPDATE public.table_sessions
        SET failed_attempts = failed_attempts + 1,
            locked_until = CASE
                WHEN failed_attempts + 1 >= 5 THEN 'infinity'::TIMESTAMPTZ
                ELSE NULL
            END
        WHERE id = v_session.id;

        IF (v_session.failed_attempts + 1) >= 5 THEN
            RETURN jsonb_build_object(
                'success', false,
                'locked', true,
                'permanent_lock', true,
                'attempts_left', 0,
                'message', '5 बार गलत पिन दर्ज किया गया। यह पिन ब्लॉक हो गया है। कृपया मैनेजर से नया पिन लें। (5 wrong attempts exceeded. This PIN is blocked. Please get a new PIN from the manager.)'
            );
        ELSE
            RETURN jsonb_build_object(
                'success', false,
                'locked', false,
                'attempts_left', 5 - (v_session.failed_attempts + 1),
                'message', 'गलत पिन! केवल ' || (5 - (v_session.failed_attempts + 1))::TEXT || ' प्रयास शेष हैं। (Invalid PIN. ' || (5 - (v_session.failed_attempts + 1))::TEXT || ' attempt(s) remaining.)'
            );
        END IF;
    END IF;
END;
$$;

-- B. MANAGER GENERATES A NEW TABLE SESSION (WITH 4-DIGIT PIN)
CREATE OR REPLACE FUNCTION public.generate_table_session(
    p_table_id UUID
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_pin TEXT;
    v_session RECORD;
    v_table RECORD;
BEGIN
    -- Check manager permission
    IF NOT public.is_manager() THEN
        -- Allow service_role or manager
        IF auth.role() <> 'service_role' THEN
            RAISE EXCEPTION 'Unauthorized: Only manager can generate table sessions.';
        END IF;
    END IF;

    SELECT * INTO v_table FROM public.cafe_tables WHERE id = p_table_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Table not found.';
    END IF;

    -- Close any existing active session for this table
    UPDATE public.table_sessions
    SET status = 'CLOSED', closed_at = now()
    WHERE table_id = p_table_id AND status = 'ACTIVE';

    -- Generate random 4-digit numeric PIN (1000 - 9999)
    v_pin := LPAD(FLOOR(random() * 9000 + 1000)::TEXT, 4, '0');

    -- Insert new active session
    INSERT INTO public.table_sessions (
        table_id,
        pin_code,
        status,
        session_token,
        failed_attempts,
        opened_at
    )
    VALUES (
        p_table_id,
        v_pin,
        'ACTIVE',
        gen_random_uuid(),
        0,
        now()
    )
    RETURNING * INTO v_session;

    RETURN jsonb_build_object(
        'session_id', v_session.id,
        'table_id', p_table_id,
        'table_number', v_table.table_number,
        'pin_code', v_pin,
        'session_token', v_session.session_token,
        'opened_at', v_session.opened_at
    );
END;
$$;

-- C. CLOSE TABLE SESSION (Manager or service_role only)
CREATE OR REPLACE FUNCTION public.close_table_session(
    p_session_id UUID
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NOT (public.is_manager() OR auth.role() = 'service_role') THEN
        RAISE EXCEPTION 'Unauthorized: Only managers can close table sessions.';
    END IF;

    UPDATE public.table_sessions
    SET status = 'CLOSED', closed_at = now()
    WHERE id = p_session_id;

    RETURN true;
END;
$$;

-- D. PLACE TABLE ORDER (Enforces DB prices & active session)
CREATE OR REPLACE FUNCTION public.place_table_order(
    p_session_token UUID,
    p_device_id TEXT,
    p_notes TEXT,
    p_items JSONB -- Array of { item_id: UUID, quantity: INTEGER, notes: TEXT }
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_session RECORD;
    v_order_id UUID;
    v_item RECORD;
    v_elem JSONB;
    v_item_id UUID;
    v_qty INTEGER;
    v_item_note TEXT;
    v_total_items INTEGER := 0;
BEGIN
    -- Verify active session
    SELECT * INTO v_session
    FROM public.table_sessions
    WHERE session_token = p_session_token AND status = 'ACTIVE';

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', 'Session is closed or invalid. Please refresh or ask manager.');
    END IF;

    -- Create order header
    INSERT INTO public.orders (
        session_id,
        table_id,
        device_id,
        status,
        notes,
        created_at
    )
    VALUES (
        v_session.id,
        v_session.table_id,
        p_device_id,
        'PENDING',
        p_notes,
        now()
    )
    RETURNING id INTO v_order_id;

    -- Loop over items and fetch actual verified prices from database
    FOR v_elem IN SELECT * FROM jsonb_array_elements(p_items)
    LOOP
        v_item_id := (v_elem->>'item_id')::UUID;
        v_qty := COALESCE((v_elem->>'quantity')::INTEGER, 1);
        v_item_note := v_elem->>'notes';

        SELECT * INTO v_item
        FROM public.menu_items
        WHERE id = v_item_id;

        IF FOUND THEN
            IF v_item.is_available = false THEN
                RAISE EXCEPTION 'Item "%" is marked not available today.', v_item.name_en;
            END IF;

            INSERT INTO public.order_items (
                order_id,
                item_id,
                item_name_en,
                item_name_hi,
                price_per_unit,
                quantity,
                item_notes,
                status
            )
            VALUES (
                v_order_id,
                v_item.id,
                v_item.name_en,
                v_item.name_hi,
                v_item.price, -- Secure DB price
                v_qty,
                v_item_note,
                'PENDING'
            );
            v_total_items := v_total_items + v_qty;
        END IF;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'order_id', v_order_id,
        'total_items', v_total_items
    );
END;
$$;

-- E. CALL WAITER (Only permitted when session is active)
CREATE OR REPLACE FUNCTION public.call_waiter_service(
    p_session_token UUID,
    p_note TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_session RECORD;
    v_table RECORD;
    v_call_id UUID;
BEGIN
    SELECT * INTO v_session
    FROM public.table_sessions
    WHERE session_token = p_session_token AND status = 'ACTIVE';

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'message', 'No active session found.');
    END IF;

    SELECT * INTO v_table FROM public.cafe_tables WHERE id = v_session.table_id;

    INSERT INTO public.waiter_calls (
        session_id,
        table_id,
        table_number,
        note,
        status,
        created_at
    )
    VALUES (
        v_session.id,
        v_session.table_id,
        v_table.table_number,
        p_note,
        'PENDING',
        now()
    )
    RETURNING id INTO v_call_id;

    RETURN jsonb_build_object('success', true, 'call_id', v_call_id);
END;
$$;

-- F. BILLING & LOYALTY (Manager executes at counter)
CREATE OR REPLACE FUNCTION public.record_bill_and_loyalty(
    p_session_id UUID,
    p_customer_name TEXT,
    p_customer_phone TEXT,
    p_discount NUMERIC DEFAULT 0
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_session RECORD;
    v_table RECORD;
    v_settings RECORD;
    v_customer RECORD;
    v_subtotal NUMERIC := 0;
    v_gst_rate NUMERIC := 5.0;
    v_gst_amount NUMERIC := 0;
    v_total NUMERIC := 0;
    v_visit_count INTEGER := 1;
    v_is_loyalty_free_coffee BOOLEAN := false;
    v_invoice_number TEXT;
    v_bill_id UUID;
BEGIN
    -- Check manager permission
    IF NOT (public.is_manager() OR auth.role() = 'service_role') THEN
        RAISE EXCEPTION 'Unauthorized: Only managers can generate and record bills.';
    END IF;

    -- 1. Fetch session
    SELECT * INTO v_session FROM public.table_sessions WHERE id = p_session_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Session not found.';
    END IF;

    SELECT * INTO v_table FROM public.cafe_tables WHERE id = v_session.table_id;
    SELECT * INTO v_settings FROM public.manager_settings WHERE id = 1;
    IF FOUND AND v_settings.gst_rate_percent IS NOT NULL THEN
        v_gst_rate := v_settings.gst_rate_percent;
    END IF;

    -- 2. Compute subtotal from all non-cancelled order items for this session
    SELECT COALESCE(SUM(oi.price_per_unit * oi.quantity), 0)
    INTO v_subtotal
    FROM public.order_items oi
    JOIN public.orders o ON oi.order_id = o.id
    WHERE o.session_id = p_session_id
      AND oi.status <> 'CANCELLED';

    -- 3. Customer & Loyalty computation
    -- "after every 5 visits the next visit has one free coffee (visit 6, 11, 16...)"
    SELECT * INTO v_customer
    FROM public.customers
    WHERE phone = TRIM(p_customer_phone);

    IF FOUND THEN
        v_visit_count := v_customer.total_visits + 1;
        -- Free coffee rule: visit 6, 11, 16, 21 ...
        IF (v_visit_count - 1) % 5 = 0 AND v_visit_count > 1 THEN
            v_is_loyalty_free_coffee := true;
        END IF;

        UPDATE public.customers
        SET name = p_customer_name,
            total_visits = v_visit_count,
            free_coffee_awarded = free_coffee_awarded + CASE WHEN v_is_loyalty_free_coffee THEN 1 ELSE 0 END,
            last_visit_at = now()
        WHERE id = v_customer.id;
    ELSE
        v_visit_count := 1;
        INSERT INTO public.customers (phone, name, total_visits, free_coffee_awarded, last_visit_at)
        VALUES (TRIM(p_customer_phone), p_customer_name, 1, 0, now())
        RETURNING * INTO v_customer;
    END IF;

    -- 4. Calculate Taxes and Final Total
    v_gst_amount := ROUND((GREATEST(v_subtotal - p_discount, 0) * v_gst_rate / 100.0), 2);
    v_total := ROUND(GREATEST(v_subtotal - p_discount, 0) + v_gst_amount, 2);

    -- 5. Generate Invoice Number
    v_invoice_number := 'INV-' || TO_CHAR(now(), 'YYYYMMDD') || '-' || LPAD(FLOOR(random() * 9000 + 1000)::TEXT, 4, '0');

    -- 6. Insert Bill
    INSERT INTO public.bills (
        invoice_number,
        session_id,
        table_id,
        table_number,
        customer_name,
        customer_phone,
        subtotal,
        discount,
        gst_rate,
        gst_amount,
        total_amount,
        visit_count,
        is_loyalty_free_coffee,
        synced_to_sheets,
        created_at
    )
    VALUES (
        v_invoice_number,
        v_session.id,
        v_session.table_id,
        v_table.table_number,
        p_customer_name,
        TRIM(p_customer_phone),
        v_subtotal,
        p_discount,
        v_gst_rate,
        v_gst_amount,
        v_total,
        v_visit_count,
        v_is_loyalty_free_coffee,
        false,
        now()
    )
    RETURNING id INTO v_bill_id;

    -- 7. Mark orders as BILLED and close session
    UPDATE public.orders
    SET status = 'BILLED'
    WHERE session_id = p_session_id;

    UPDATE public.table_sessions
    SET status = 'CLOSED', closed_at = now()
    WHERE id = p_session_id;

    RETURN jsonb_build_object(
        'bill_id', v_bill_id,
        'invoice_number', v_invoice_number,
        'subtotal', v_subtotal,
        'discount', p_discount,
        'gst_rate', v_gst_rate,
        'gst_amount', v_gst_amount,
        'total_amount', v_total,
        'visit_count', v_visit_count,
        'is_loyalty_free_coffee', v_is_loyalty_free_coffee,
        'table_number', v_table.table_number,
        'customer_name', p_customer_name,
        'customer_phone', p_customer_phone
    );
END;
$$;

-- G. 30-DAY RETENTION CLEANUP
-- "Supabase keeps only 30 days of closed bills"
CREATE OR REPLACE FUNCTION public.cleanup_old_closed_bills()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_deleted_count INTEGER := 0;
BEGIN
    IF NOT (public.is_manager() OR auth.role() = 'service_role') THEN
        RAISE EXCEPTION 'Unauthorized: Only manager can run retention cleanup.';
    END IF;

    -- Delete bills older than 30 days
    WITH deleted AS (
        DELETE FROM public.bills
        WHERE created_at < (now() - INTERVAL '30 days')
        RETURNING id
    )
    SELECT COUNT(*) INTO v_deleted_count FROM deleted;

    -- Delete closed table sessions older than 30 days
    DELETE FROM public.table_sessions
    WHERE status = 'CLOSED' AND closed_at < (now() - INTERVAL '30 days');

    RETURN v_deleted_count;
END;
$$;

