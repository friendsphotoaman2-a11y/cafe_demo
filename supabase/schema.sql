-- 1. allowed_managers: Only authenticated users can read, managers can manage
CREATE POLICY "Managers can read allowed_managers" ON public.allowed_managers
    FOR SELECT TO authenticated USING (true);

-- 2. cafe_tables: Public can read tables (to view table code/number), managers full access
CREATE POLICY "Public can view tables" ON public.cafe_tables
    FOR SELECT TO public USING (true);

CREATE POLICY "Managers can manage tables" ON public.cafe_tables
    FOR ALL TO authenticated USING (public.is_manager());

-- 3. table_sessions:
-- Managers full access; public has NO direct select (sessions protected, pin_code never exposed to PostgREST queries)
CREATE POLICY "Managers can manage sessions" ON public.table_sessions
    FOR ALL TO authenticated USING (public.is_manager());

-- 4. categories: Public read-only, managers write
CREATE POLICY "Public can read categories" ON public.categories
    FOR SELECT TO public USING (true);

CREATE POLICY "Managers can manage categories" ON public.categories
    FOR ALL TO authenticated USING (public.is_manager());

-- 5. menu_items: Public read-only, managers write
CREATE POLICY "Public can read menu items" ON public.menu_items
    FOR SELECT TO public USING (true);

CREATE POLICY "Managers can manage menu items" ON public.menu_items
    FOR ALL TO authenticated USING (public.is_manager());

-- 6. orders:
-- Managers full access; public has NO direct select (cross-table data leak eliminated, tables read via /api/table/orders)
CREATE POLICY "Managers can manage all orders" ON public.orders
    FOR ALL TO authenticated USING (public.is_manager());

-- 7. order_items:
-- Managers full access; public has NO direct select
CREATE POLICY "Managers can manage order items" ON public.order_items
    FOR ALL TO authenticated USING (public.is_manager());

-- 8. waiter_calls:
-- Managers full access; public has NO direct select
CREATE POLICY "Managers can manage waiter calls" ON public.waiter_calls
    FOR ALL TO authenticated USING (public.is_manager());

-- 9. customers & bills & settings:
CREATE POLICY "Managers can manage customers" ON public.customers
    FOR ALL TO authenticated USING (public.is_manager());

CREATE POLICY "Managers can manage bills" ON public.bills
    FOR ALL TO authenticated USING (public.is_manager());

CREATE POLICY "Public can read manager settings" ON public.manager_settings
    FOR SELECT TO public USING (true);

CREATE POLICY "Managers can manage settings" ON public.manager_settings
