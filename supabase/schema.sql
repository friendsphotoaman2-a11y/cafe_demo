-- 2. MANAGER ALLOWLIST TABLE
CREATE TABLE IF NOT EXISTS public.allowed_managers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT NOT NULL UNIQUE,
    full_name TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Helper function: Check if current authenticated user is an allowed manager
CREATE OR REPLACE FUNCTION public.is_manager()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.allowed_managers
    WHERE LOWER(email) = LOWER(COALESCE(auth.jwt() ->> 'email', ''))
  );
$$;

-- 3. CAFE TABLES
CREATE TABLE IF NOT EXISTS public.cafe_tables (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_number TEXT NOT NULL,
    table_code TEXT NOT NULL UNIQUE, -- e.g. T1, T2, T3 (used in /t/<table_code>)
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 4. TABLE SESSIONS (One active session per table, protected by 4-digit PIN)
CREATE TABLE IF NOT EXISTS public.table_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_id UUID NOT NULL REFERENCES public.cafe_tables(id) ON DELETE CASCADE,
    pin_code TEXT NOT NULL, -- 4-digit PIN generated by manager
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED')),
    session_token UUID NOT NULL DEFAULT gen_random_uuid(), -- Bearer token granted on correct PIN entry
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ, -- Set to now() + 5 mins after 5 wrong attempts
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_sessions_table_status ON public.table_sessions(table_id, status);
CREATE INDEX IF NOT EXISTS idx_sessions_token ON public.table_sessions(session_token);

-- 5. MENU CATEGORIES
