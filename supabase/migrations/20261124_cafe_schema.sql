-- ==============================================================================
-- SUPABASE MIGRATION: CAFE SYSTEM DATABASE SCHEMA
-- ==============================================================================
-- Tables created:
-- 1.  cafe_settings
-- 2.  staff_emails
-- 3.  tables (table_code unique)
-- 4.  table_sessions (pin, status open/closed, opened_at, expires_at, closed_at)
--     * With partial unique index: Only one open session per table
-- 5.  session_members
-- 6.  pin_attempts
-- 7.  menu_categories (name_en, name_hi, available_from, available_to)
-- 8.  menu_items (name_en, name_hi, price, is_veg, photo_url, is_available_today, available_from, available_to)
-- 9.  orders
-- 10. order_items (name_snapshot, price_snapshot, qty, note, status)
-- 11. waiter_calls
-- 12. bills (order_code unique, customer_name, phone, subtotal, tax, total, visit_no, free_visit, payment_mode, synced_to_sheet)
-- 13. audit_log
-- Realtime publication configured for live updating tables.
-- ==============================================================================

-- 0. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. CAFE SETTINGS
CREATE TABLE IF NOT EXISTS public.cafe_settings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    cafe_name TEXT NOT NULL DEFAULT 'Brew & Bites Cafe',
    address TEXT,
    phone TEXT,
    gstin TEXT,
    tax_rate_percent NUMERIC(5,2) NOT NULL DEFAULT 5.0,
    receipt_paper_size TEXT NOT NULL DEFAULT '80mm' CHECK (receipt_paper_size IN ('58mm', '80mm')),
    kitchen_screen_enabled BOOLEAN NOT NULL DEFAULT true,
    google_sheet_id TEXT DEFAULT '1lqe2AlMhSUuXPcVIUBryfBUiL-us8r_5DzPDTwcCMUY',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. STAFF / MANAGER EMAILS (Allowlist)
CREATE TABLE IF NOT EXISTS public.staff_emails (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email TEXT NOT NULL UNIQUE,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'manager' CHECK (role IN ('manager', 'admin', 'staff')),
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_staff_emails_email ON public.staff_emails(email);

-- 3. TABLES
CREATE TABLE IF NOT EXISTS public.tables (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_code TEXT NOT NULL UNIQUE, -- e.g. 'T1', 'T2', 'T3'
    table_name TEXT,                 -- e.g. 'Table 1'
    qr_slug TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tables_code ON public.tables(table_code);

-- 4. TABLE SESSIONS
CREATE TABLE IF NOT EXISTS public.table_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_id UUID NOT NULL REFERENCES public.tables(id) ON DELETE CASCADE,
    pin TEXT NOT NULL, -- 4-digit PIN generated by manager
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    session_token UUID NOT NULL DEFAULT gen_random_uuid(),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_table_sessions_table ON public.table_sessions(table_id);
CREATE INDEX IF NOT EXISTS idx_table_sessions_token ON public.table_sessions(session_token);

-- CRITICAL RULE: Only one open session per table (Partial Unique Index)
CREATE UNIQUE INDEX IF NOT EXISTS idx_single_open_session_per_table
    ON public.table_sessions(table_id)
    WHERE status = 'open';

-- 5. SESSION MEMBERS (Tracks active client devices connected to a table session)
CREATE TABLE IF NOT EXISTS public.session_members (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.table_sessions(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL, -- Unique client device identifier from localStorage
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_session_device UNIQUE (session_id, device_id)
);

CREATE INDEX IF NOT EXISTS idx_session_members_session ON public.session_members(session_id);

-- 6. PIN ATTEMPTS (For security audit & rate limiting / lockout)
CREATE TABLE IF NOT EXISTS public.pin_attempts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    table_id UUID REFERENCES public.tables(id) ON DELETE CASCADE,
    session_id UUID REFERENCES public.table_sessions(id) ON DELETE CASCADE,
    attempted_pin TEXT NOT NULL,
    ip_address TEXT,
    is_successful BOOLEAN NOT NULL DEFAULT false,
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_pin_attempts_table_time ON public.pin_attempts(table_id, attempted_at);

-- 7. MENU CATEGORIES
CREATE TABLE IF NOT EXISTS public.menu_categories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name_en TEXT NOT NULL,
    name_hi TEXT NOT NULL,
    available_from TIME, -- e.g. 07:00:00 for breakfast
    available_to TIME,   -- e.g. 11:30:00
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 8. MENU ITEMS
CREATE TABLE IF NOT EXISTS public.menu_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    category_id UUID REFERENCES public.menu_categories(id) ON DELETE SET NULL,
    name_en TEXT NOT NULL,
    name_hi TEXT NOT NULL,
    price NUMERIC(10,2) NOT NULL CHECK (price >= 0),
    is_veg BOOLEAN NOT NULL DEFAULT true,
    photo_url TEXT,
    is_available_today BOOLEAN NOT NULL DEFAULT true,
    available_from TIME,
    available_to TIME,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_menu_items_category ON public.menu_items(category_id);
CREATE INDEX IF NOT EXISTS idx_menu_items_available ON public.menu_items(is_available_today);

-- 9. ORDERS
CREATE TABLE IF NOT EXISTS public.orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.table_sessions(id) ON DELETE CASCADE,
    table_id UUID NOT NULL REFERENCES public.tables(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'preparing', 'ready', 'served', 'billed', 'cancelled')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_orders_session ON public.orders(session_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);

-- 10. ORDER ITEMS
CREATE TABLE IF NOT EXISTS public.order_items (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_id UUID NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    menu_item_id UUID REFERENCES public.menu_items(id) ON DELETE SET NULL,
    name_snapshot TEXT NOT NULL, -- Frozen name at order placement
    price_snapshot NUMERIC(10,2) NOT NULL CHECK (price_snapshot >= 0), -- Frozen server-verified price
    qty INTEGER NOT NULL CHECK (qty > 0),
    note TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'preparing', 'ready', 'served', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_order_items_order ON public.order_items(order_id);

-- 11. WAITER CALLS
CREATE TABLE IF NOT EXISTS public.waiter_calls (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.table_sessions(id) ON DELETE CASCADE,
    table_id UUID NOT NULL REFERENCES public.tables(id) ON DELETE CASCADE,
    note TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_waiter_calls_session ON public.waiter_calls(session_id);
CREATE INDEX IF NOT EXISTS idx_waiter_calls_status ON public.waiter_calls(status);

-- 12. BILLS
CREATE TABLE IF NOT EXISTS public.bills (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    order_code TEXT NOT NULL UNIQUE, -- e.g. 'ORD-20261124-001'
    session_id UUID REFERENCES public.table_sessions(id) ON DELETE SET NULL,
    table_id UUID REFERENCES public.tables(id) ON DELETE SET NULL,
    customer_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
    tax NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (tax >= 0),
    total NUMERIC(10,2) NOT NULL CHECK (total >= 0),
    visit_no INTEGER NOT NULL DEFAULT 1 CHECK (visit_no > 0),
    free_visit BOOLEAN NOT NULL DEFAULT false,
    payment_mode TEXT NOT NULL DEFAULT 'counter' CHECK (payment_mode IN ('counter', 'cash', 'upi', 'card')),
    synced_to_sheet BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bills_phone ON public.bills(phone);
CREATE INDEX IF NOT EXISTS idx_bills_order_code ON public.bills(order_code);
CREATE INDEX IF NOT EXISTS idx_bills_created_at ON public.bills(created_at);

-- 13. AUDIT LOG
CREATE TABLE IF NOT EXISTS public.audit_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    actor_email TEXT,
    action TEXT NOT NULL,        -- e.g. 'PIN_GENERATED', 'BILL_SETTLED', 'AVAILABILITY_CHANGED'
    entity_type TEXT NOT NULL,   -- e.g. 'table_sessions', 'menu_items', 'bills'
    entity_id TEXT,
    details JSONB,
    ip_address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_action ON public.audit_log(action);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON public.audit_log(created_at);

